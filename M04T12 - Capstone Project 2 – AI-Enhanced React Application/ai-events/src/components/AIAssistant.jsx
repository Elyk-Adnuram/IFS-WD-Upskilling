import {useEffect} from 'react';
import {useAI} from '../context/AIContext.jsx';
import {AI_KINDS} from '../services/aiService.js';

/**
 * AI event assistant. Drafts are shown in an editable panel and only reach
 * the event when the user chooses to add them.
 */
export default function AIAssistant({details, onApply}) {
  const {
    status, kind, draft, error, simulated, generate, setDraft, reset,
  } = useAI();
  const canGenerate = details.name.trim().length > 0;
  const loading = status === 'loading';

  // Clear any leftover draft when leaving the form.
  useEffect(() => reset, [reset]);

  const handleApply = () => {
    onApply(kind, draft.trim());
    reset();
  };

  return (
    <section className="ai-panel" aria-labelledby="ai-heading">
      <div className="ai-panel__head">
        <h3 id="ai-heading">AI event assistant</h3>
        <span className="badge badge--ai">AI</span>
      </div>
      <p className="muted">
        Enter an event name, then let AI draft text for you to review.
      </p>
      <div className="row">
        {Object.entries(AI_KINDS).map(([key, label]) => (
          <button
            key={key}
            type="button"
            className="btn btn--ai"
            disabled={!canGenerate || loading}
            onClick={() => generate(key, details)}>
            {label}
          </button>
        ))}
      </div>
      {!canGenerate && <p className="muted">Add an event name to enable AI.</p>}

      <div aria-live="polite">
        {loading && (
          <p className="ai-status" role="status">
            <span className="spinner" aria-hidden="true" /> Generating with AI...
          </p>
        )}
        {status === 'error' && (
          <div className="alert alert--error" role="alert">
            <p>{error}</p>
            <button type="button" className="btn btn--small"
              onClick={() => generate(kind, details)}>
              Try again
            </button>
          </div>
        )}
      </div>

      {status === 'success' && (
        <div className="ai-draft">
          <label htmlFor="ai-draft">
            AI-generated draft{simulated && ' (simulated demo response)'}
          </label>
          <textarea
            id="ai-draft"
            rows={6}
            value={draft}
            onChange={(e) => setDraft(e.target.value)} />
          <p className="notice">
            This content was generated by AI and may contain inaccuracies.
            Please review before saving.
          </p>
          <div className="row">
            <button type="button" className="btn" onClick={handleApply}
              disabled={!draft.trim()}>
              Add to description
            </button>
            <button type="button" className="btn btn--ghost" onClick={reset}>
              Discard
            </button>
          </div>
        </div>
      )}
    </section>
  );
}
